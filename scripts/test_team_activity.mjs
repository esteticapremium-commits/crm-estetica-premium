import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';
const source = await readFile(new URL('../src/teamPresenceLogic.ts', import.meta.url), 'utf8');
const { code } = await transform(source, { loader: 'ts', format: 'esm' });
const { isPresenceActive, presenceDuration } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
assert.equal(isPresenceActive(true, true, 0, 0), true);
assert.equal(isPresenceActive(true, true, 0, 299999), true);
assert.equal(isPresenceActive(true, true, 0, 300000), false);
assert.equal(isPresenceActive(false, true, 0, 100), false);
assert.equal(isPresenceActive(true, false, 0, 100), false);
assert.equal(isPresenceActive(true, true, 1000, 100), false);
assert.equal(presenceDuration(-20), '0 s');
assert.equal(presenceDuration(0), '0 s');
assert.equal(presenceDuration(59), '59 s');
assert.equal(presenceDuration(60), '1 min');
assert.equal(presenceDuration(3661), '1 h 1 min');
const app = await readFile(new URL('../src/App.tsx', import.meta.url), 'utf8');
assert.match(app, /tab === "team" && isAdmin && currentClient/);
const sql = await readFile(new URL('../supabase/upgrade_team_activity.sql', import.meta.url), 'utf8');
assert.match(sql, /range_agg\(span\)/);
assert.match(sql, /revoke all on public.team_presence_settings, public.team_presence_sessions, public.team_presence_intervals from anon, authenticated/);
assert.match(sql, /role = 'admin'/);
assert.match(sql, /revoke all on function public.team_activity_report\(uuid,date,date\) from public, anon/);
assert.match(sql, /v_session.user_id <> v_user/);
console.log('Test presenza: attività/inattività, focus, durate e guardie di accesso OK');
